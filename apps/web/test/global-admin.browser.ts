test('Share links: two activations exhaust a standard link and preserve independent account data', async ({ page, browser, scenario: f }, info) => {
  await login(page, f); await people(page, f)
  await page.getByLabel('Máximo de cuentas').fill('2')
  await page.getByLabel('Vigencia del enlace (días)').fill('1')
  await page.getByRole('button', { name: 'Crear enlace compartible', exact: true }).click()
  const url = await page.getByLabel('Enlace compartible de invitación', { exact: true }).inputValue()
  for (let i = 0; i < 2; i++) {
    const guest = await accountContext(browser, info)
    try {
      const other = await guest.newPage(); await other.goto(url)
      await other.getByLabel('Tu nombre', { exact: true }).fill(`Shared guest ${i}`)
      await other.getByLabel('Correo electrónico', { exact: true }).fill(`shared-${i}@example.test`)
      await other.getByLabel(/^Contraseña/).fill(f.password)
      await other.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click()
      await expect(other).toHaveURL(`${f.origin}/app`)
      await expect(other.getByText('Tu primer proyecto empieza acá.', { exact: true })).toBeVisible()
      const current = await (await guest.request.get(`${f.origin}/api/me`)).json()
      expect(current.user.role).toBe('user'); expect(current.user.canInvite).toBe(false)
      expect((await (await guest.request.get(`${f.origin}/api/credits`)).json()).balance).toBe(100)
      await other.goto(`${f.origin}/app/credits`)
      await expect(other.getByTestId('credit-balance')).toHaveText('100')
    } finally { await guest.close() }
    await page.reload()
    await expect(page.locator('article').filter({ hasText: 'Invitación compartible' })).toContainText(`Cuentas creadas: ${i + 1}/2`)
  }
  const exhausted = page.locator('article').filter({ hasText: 'Invitación compartible' })
  await expect(exhausted).toContainText('Límite alcanzado')
  await expect(exhausted.getByRole('button', { name: 'Revocar invitación' })).toBeDisabled()
  const guest = await accountContext(browser, info)
  try {
    const other = await guest.newPage(); await other.goto(url)
    await expect(other.getByRole('alert')).toBeVisible()
    await expect(other.getByRole('button', { name: 'Crear mi cuenta', exact: true })).toHaveCount(0)
  } finally { await guest.close() }
  expect((await f.database.db.selectFrom('t3_invite_redemption').selectAll().execute()).length).toBe(2)
  await evidence(page, info, 'share-link-redemption')
})

