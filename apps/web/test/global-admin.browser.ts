import { test as base, expect, type Browser, type Page, type TestInfo } from '@playwright/test'
import { globalAdminFixture, login, seedUsage, type AdminFixture } from './global-admin-fixture.ts'

const test = base.extend<{ scenario: AdminFixture }>({
  scenario: async ({ browser }, use) => { void browser; const f = await globalAdminFixture(); try { await use(f) } finally { await f.close() } },
})
const people = async (page: Page, f: AdminFixture) => { await page.goto(`${f.origin}/app/users`); await expect(page.getByRole('heading', { name: 'Standard QA', exact: true })).toBeVisible() }
let pageErrors: string[] = []
const watchErrors = (page: Page) => { page.on('pageerror', error => pageErrors.push(error.message)) }
test.beforeEach(({ page }) => { pageErrors = []; watchErrors(page) })
test.afterEach(() => { expect(pageErrors).toEqual([]) })
async function accountContext(browser: Browser, info: TestInfo) {
  const context = await browser.newContext({ locale: 'es-AR', timezoneId: 'America/Argentina/Buenos_Aires', viewport: info.project.use.viewport, hasTouch: info.project.use.hasTouch, isMobile: info.project.use.isMobile })
  context.on('page', watchErrors)
  return context
}
const person = (page: Page, name: string) => page.locator('article').filter({ has: page.getByRole('heading', { name, exact: true }) })
async function evidence(page: Page, info: TestInfo, name: string) {
  await expect(page.locator('h1').first()).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: /^Cargando/ })).toHaveCount(0)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: info.outputPath(`${name}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

