import { expect, test } from '@playwright/test'
import { foundationAgentFixture, projectPath } from './foundation-agent-fixture'

test.use({ locale: 'es-AR' })

test('energy and daylight share a saved solar moment across panels and both floors', async ({ page }) => {
  const server = await foundationAgentFixture(page)
  server.makeReady(true)
  const before = server.saved()
  await page.goto(projectPath)
  const toggle = page.locator('summary').filter({ hasText: /^Energía solar del edificio$/ })
  await toggle.click()
  const energy = page.getByRole('region', { name: 'Energía solar del edificio', exact: true })
  const time = energy.getByRole('slider', { name: /^Hora local/ })
  const save = page.getByRole('button', { name: 'Guardar cambios', exact: true })
  await expect(save).toBeDisabled()
  await time.press('End')
  await expect(time).toHaveValue('1439')
  await expect(save).toBeEnabled()
  await expect(page.locator('summary').filter({ hasText: /^Luz natural · fecha y hora/ })).toContainText('23:59')
  await energy.getByLabel('Fecha del estudio', { exact: true }).fill('2026-12-21')
  await save.click()
  await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  const firstSave = server.saved()
  expect(firstSave.scene?.solar.date).toBe('2026-12-21')
  expect(firstSave.scene?.solar.selected.minutes).toBe(1439)
  for (const level of firstSave.foundationModels!.levels) {
    expect(level.scene.solar).toEqual(firstSave.scene!.solar)
    const original = before.foundationModels!.levels.find(item => item.id === level.id)!
    expect(level.scene.fixtures).toEqual(original.scene.fixtures)
    expect(level.scene.editor).toEqual(original.scene.editor)
  }
  await toggle.click(); await toggle.click()
  await expect(time).toHaveValue('1439')
  await expect(energy.getByLabel('Fecha del estudio', { exact: true })).toHaveValue('2026-12-21')

  const daylight = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Luz natural · fecha y hora/ }) })
  await daylight.locator('summary').click()
  await daylight.getByLabel('Fecha del estudio', { exact: true }).fill('2026-06-21')
  await daylight.getByLabel('Hora del edificio', { exact: true }).fill('09:45')
  await daylight.getByRole('button', { name: 'Aplicar fecha y hora', exact: true }).click()
  await expect(energy.getByLabel('Fecha del estudio', { exact: true })).toHaveValue('2026-06-21')
  await expect(time).toHaveValue('585')
  await page.getByRole('combobox', { name: 'Planta', exact: true }).selectOption('upper')
  await expect(time).toHaveValue('585')
  await expect(page.locator('summary').filter({ hasText: /^Luz natural · fecha y hora/ })).toContainText('09:45')
  await save.click()
  await expect(save).toBeDisabled()
  await page.reload()
  await toggle.click()
  await expect(time).toHaveValue('585')
  await expect(energy.getByLabel('Fecha del estudio', { exact: true })).toHaveValue('2026-06-21')
  expect(server.saved().foundationModels!.levels.every(level => level.scene.solar.selected.minutes === 585 && level.scene.solar.date === '2026-06-21')).toBe(true)
  expect(server.starts).toHaveLength(0)
})
