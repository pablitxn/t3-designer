import { expect, test as base, type Page } from '@playwright/test'
import { startSharedEditorScenario, type SharedEditorScenario } from './shared-editor-fixture.ts'

type Seed = Awaited<ReturnType<SharedEditorScenario['seed']>>
const test = base.extend<{ seed: Seed; evidence: void }, { scenario: SharedEditorScenario }>({
  // Playwright requires destructuring even for a worker fixture without dependencies.
  // eslint-disable-next-line no-empty-pattern
  scenario: [async ({}, use) => { const scenario = await startSharedEditorScenario(); try { await use(scenario) } finally { await scenario.close() } }, { scope: 'worker' }],
  seed: async ({ scenario }, use) => { await use(await scenario.seed()) },
  evidence: [async ({ page, browser }, use) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await test.info().attach('browser-context', { body: JSON.stringify({ engine: test.info().project.use.browserName,
      version: browser.version(), viewport: page.viewportSize(), hasTouch: test.info().project.use.hasTouch ?? false,
      isMobile: test.info().project.use.isMobile ?? false, physicalDevice: false }), contentType: 'application/json' })
    await use()
    expect(errors).toEqual([])
  }, { auto: true }],
})
async function login(page: Page, scenario: SharedEditorScenario, email: string) {
  await page.goto(`${scenario.origin}/login`)
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(scenario.password)
  await page.getByRole('button', { name: /^Iniciar sesión/ }).click()
  await expect(page).toHaveURL(`${scenario.origin}/app`)
}
async function open(page: Page, scenario: SharedEditorScenario, seed: Seed) {
  await login(page, scenario, seed.editor.email)
  await page.getByRole('heading', { name: seed.project.name, exact: true }).getByRole('link').click()
  await expect(page.getByLabel('Variantes del departamento')).toBeVisible()
}
async function stored(scenario: SharedEditorScenario, seed: Seed) { return scenario.projects.get(seed.owner, seed.project.id) }
async function notes(page: Page, value: string) { await page.getByLabel(/^Notas del proyecto/).fill(value) }
async function save(page: Page) {
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
}
async function section(page: Page, title: string) {
  const panel = page.getByLabel('Terminaciones e iluminación', { exact: true })
  const detail = panel.locator('details').filter({ has: page.locator('summary').filter({ hasText: title }) }).first()
  if (await detail.getAttribute('open') === null) await detail.locator('summary').click()
}
async function screenshot(page: Page, name: string) { await page.screenshot({ path: test.info().outputPath(`${name}.png`), fullPage: true }) }

