import { expect, test } from '@playwright/test'
import { foundationAgentFixture as fixture, projectPath } from './foundation-agent-fixture'

test.use({ locale: 'es-AR' })

test.use({ viewport: { width: 1440, height: 1100 }, launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'], ...(process.env.T3_PLAYWRIGHT_CHANNEL ? { channel: process.env.T3_PLAYWRIGHT_CHANNEL } : {}) } })
test('both agent candidates render actual WebGL geometry and allow inspection of another floor', { tag: '@webgl' }, async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && /shader|WebGL|THREE/.test(message.text())) errors.push(message.text()) })
  const server = await fixture(page)
  server.seedRun('dwelling'); server.complete()
  server.seedRun('building'); server.complete('building')
  await page.goto(projectPath)
  for (const target of ['dwelling', 'building'] as const) {
    const workshop = page.getByTestId(`foundation-agent-${target}`)
    const preview = workshop.getByRole('region', { name: 'Vista previa del modelo', exact: true })
    const canvas = preview.locator('canvas')
    await expect(canvas).toBeVisible({ timeout: 30_000 })
    await canvas.scrollIntoViewIfNeeded()
    expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    const bounds = await canvas.boundingBox()
    expect(bounds!.width).toBeGreaterThan(400)
    expect(bounds!.height).toBeGreaterThan(250)
    if (target === 'dwelling') {
      await workshop.getByRole('combobox', { name: 'Planta de la propuesta', exact: true }).selectOption('upper')
      await expect(workshop.getByRole('combobox', { name: 'Planta de la propuesta', exact: true })).toHaveValue('upper')
      await expect(canvas).toBeVisible()
      expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
      await preview.getByRole('button', { name: 'Vista cenital', exact: true }).click()
      await expect(preview.getByRole('button', { name: 'Vista cenital', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(canvas).toBeVisible()
      await preview.getByRole('checkbox', { name: 'Ver todas las plantas', exact: true }).check()
      await expect(preview.getByText('Cota de planta: 2,9 m', { exact: true })).toBeVisible()
      await preview.getByText('Conexiones entre plantas', { exact: true }).click()
      await expect(preview.getByText('No hay conexiones entre plantas documentadas en esta propuesta.', { exact: true })).toBeVisible()
      await preview.getByRole('button', { name: 'Perspectiva', exact: true }).click()
      expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
      await preview.getByRole('checkbox', { name: 'Ver todas las plantas', exact: true }).uncheck()
    }
    await preview.screenshot({ path: `/tmp/t3-foundation-agent-${target}-webgl.png`, animations: 'disabled' })
    await testInfo.attach(`${target}-webgl-preview`, { path: `/tmp/t3-foundation-agent-${target}-webgl.png`, contentType: 'image/png' })
    if (target === 'building') {
      await preview.getByRole('button', { name: 'Edificio principal', exact: true }).click()
      await expect(preview.getByRole('button', { name: 'Edificio principal', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(canvas).toBeVisible()
      expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
      await preview.getByRole('button', { name: 'Entorno', exact: true }).click()
      await expect(preview.getByRole('button', { name: 'Entorno', exact: true })).toHaveAttribute('aria-pressed', 'true')
    }
    if (target === 'dwelling') {
      await workshop.evaluate(element => element.scrollIntoView({ block: 'start' }))
      await page.screenshot({ path: '/tmp/t3-foundation-agent-desktop.png', animations: 'disabled' })
    }
  }
  expect(errors).toEqual([])
  expect(server.starts).toHaveLength(0)
})

test('a building geometry correction preserves every floor layout, furniture and original plan reference', { tag: '@webgl' }, async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const server = await fixture(page)
  server.makeReady(true)
  server.seedRun('building')
  const originalBuilding = server.complete('building')
  if (originalBuilding.candidate?.target !== 'building') throw new Error('Expected a building candidate')
  const sourceTarget = structuredClone(originalBuilding.candidate.buildings.find(building => building.isTarget)!)
  const heightQuote = `La altura del cuerpo sin cubierta debe ser ${sourceTarget.height + 3} metros.`
  const fixtureId = server.saved().scene!.fixtures[0].id
  await page.goto(projectPath)
  const floor = page.getByRole('combobox', { name: 'Planta', exact: true })
  const editor = page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })
  await floor.selectOption('upper')
  await editor.getByLabel('Nombre de la copia', { exact: true }).fill('Distribución que debe conservarse')
  await editor.getByRole('button', { name: 'Duplicar distribución', exact: true }).click()
  await editor.getByRole('combobox', { name: /^Objetos colocados/ }).selectOption(fixtureId)
  const x = editor.getByLabel('X (m)', { exact: true })
  await x.fill('3.6'); await x.blur()
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  const before = server.saved()
  await page.locator('summary').filter({ hasText: /^Agentes de vivienda y edificio$/ }).click()
  const workshop = page.getByTestId('foundation-agent-building')
  await workshop.getByLabel('Tu corrección', { exact: true }).fill(`${heightQuote} Conservá las distribuciones y los muebles de ambas plantas.`)
  await workshop.getByRole('button', { name: 'Enviar corrección', exact: false }).click()
  await expect.poll(() => server.starts.length).toBe(1)
  expect(server.starts[0].body.parentVersionId).toBe(originalBuilding.id)
  const revised = server.complete('building')
  if (revised.candidate?.target !== 'building') throw new Error('Expected a building candidate')
  const revisedTarget = revised.candidate.buildings.find(building => building.isTarget)!
  revisedTarget.height += 3
  revised.candidate.buildingCorrections = { baseBuildings: [sourceTarget], operations: [{ type: 'set_height', buildingId: revisedTarget.id, value: revisedTarget.height, quote: heightQuote }] }
  await expect(workshop.getByRole('button', { name: 'Usar esta versión', exact: true })).toBeVisible()
  const proposedHeight = new Intl.NumberFormat('es-AR', { maximumFractionDigits: 2 }).format(revisedTarget.height + revisedTarget.roofHeight)
  await expect(workshop.getByText(`Altura: ${proposedHeight} m`, { exact: false })).toBeVisible()
  const heightRow = workshop.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'Altura del cuerpo', exact: true }) })
  await expect(heightRow.getByRole('cell')).toHaveText([`${new Intl.NumberFormat('es-AR').format(sourceTarget.height)} m`, `${new Intl.NumberFormat('es-AR').format(revisedTarget.height)} m`])
  await expect(workshop.getByText(`Indicación del usuario: «${heightQuote}»`, { exact: true })).toBeVisible()
  await workshop.getByRole('button', { name: 'Usar esta versión', exact: true }).click()
  await expect(workshop.getByText('✓ Aplicada al proyecto', { exact: true })).toBeVisible()
  expect(server.confirmations.at(-1)).toContain('Se conservan los muebles y las distribuciones de cada planta')
  expect(server.saved().foundationModels?.activeLevelId).toBe('upper')
  expect(server.saved().foundations).toEqual(before.foundations)
  for (const previous of before.foundationModels!.levels) {
    const current = server.saved().foundationModels!.levels.find(level => level.id === previous.id)!.scene
    expect(current.apartment).toEqual(previous.scene.apartment)
    expect(current.editor).toEqual(previous.scene.editor)
    expect(current.fixtures).toEqual(previous.scene.fixtures)
    expect(current.buildings.find(building => building.isTarget)?.height).toBe(revisedTarget.height)
  }
  await page.reload()
  await expect(floor).toHaveValue('upper')
  await editor.getByRole('combobox', { name: /^Objetos colocados/ }).selectOption(fixtureId)
  await expect(x).toHaveValue('3.6')
  await expect(editor.getByRole('combobox', { name: 'Distribuciones', exact: true }).locator('option')).toHaveCount(2)
  await floor.selectOption('ground')
  await editor.getByRole('combobox', { name: /^Objetos colocados/ }).selectOption(fixtureId)
  await expect(x).toHaveValue('2')
  await expect(editor.getByRole('combobox', { name: 'Distribuciones', exact: true }).locator('option')).toHaveCount(1)
  await page.locator('summary').filter({ hasText: /^Planos y fuentes originales$/ }).click()
  await expect(page.getByRole('link', { name: /planta-baja.png/ })).toHaveAttribute('href', /\/references\/[^/]+\/image$/)
  await expect(page.getByRole('link', { name: /dormitorios.png/ })).toHaveAttribute('href', /\/references\/[^/]+\/image$/)
  expect(errors).toEqual([])
})

test('ready floors keep independent furniture and layout versions when switching, saving and reloading', { tag: '@webgl' }, async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && /shader|WebGL|THREE/.test(message.text())) errors.push(message.text()) })
  const server = await fixture(page)
  server.makeReady(true)
  const fixtureId = server.saved().scene!.fixtures[0].id
  await page.goto(projectPath)
  const floor = page.getByRole('combobox', { name: 'Planta', exact: true })
  await expect(floor).toHaveValue('ground')
  const editor = page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })
  const canvas = editor.locator('canvas').first()
  await expect(canvas).toBeVisible({ timeout: 30_000 })
  expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
  const selectFixture = async () => { await editor.getByRole('combobox', { name: /^Objetos colocados/ }).selectOption(fixtureId) }
  await selectFixture()
  const x = editor.getByLabel('X (m)', { exact: true })
  await expect(x).toHaveValue('2')
  await x.fill('2.4'); await x.blur()
  await floor.selectOption('upper')
  await selectFixture()
  await expect(x).toHaveValue('3')
  await editor.getByLabel('Nombre de la copia', { exact: true }).fill('Dormitorio flexible')
  await editor.getByRole('button', { name: 'Duplicar distribución', exact: true }).click()
  await selectFixture()
  await x.fill('3.2'); await x.blur()
  await expect(editor.getByRole('combobox', { name: 'Distribuciones', exact: true }).locator('option')).toHaveCount(2)
  await floor.selectOption('ground')
  await selectFixture()
  await expect(x).toHaveValue('2.4')
  await expect(editor.getByRole('combobox', { name: 'Distribuciones', exact: true }).locator('option')).toHaveCount(1)
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  expect(server.writes).toHaveLength(1)
  expect(server.saved().foundationModels?.levels.map(level => level.scene.fixtures[0].position[0])).toEqual([2.4, 3.2])
  await page.reload()
  await expect(floor).toHaveValue('ground')
  await selectFixture()
  await expect(x).toHaveValue('2.4')
  await floor.selectOption('upper')
  await selectFixture()
  await expect(x).toHaveValue('3.2')
  await expect(editor.getByRole('combobox', { name: 'Distribuciones', exact: true }).locator('option')).toHaveCount(2)
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(floor).toHaveValue('upper')
  await expect(canvas).toBeVisible({ timeout: 30_000 })
  expect(await canvas.evaluate(element => !!(element as HTMLCanvasElement).getContext('webgl2'))).toBe(true)
  await canvas.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/t3-foundation-ready-multilevel.png', animations: 'disabled' })
  await testInfo.attach('ready-multilevel', { path: '/tmp/t3-foundation-ready-multilevel.png', contentType: 'image/png' })
  expect(server.saved().foundationModels?.activeLevelId).toBe('upper')
  expect(errors).toEqual([])
})

test('a viewer can inspect another ready floor without making project changes', { tag: '@webgl' }, async ({ page }) => {
  test.setTimeout(60_000)
  const server = await fixture(page, 'viewer')
  server.makeReady(true)
  await page.goto(projectPath)
  const floor = page.getByRole('combobox', { name: 'Planta', exact: true })
  await floor.selectOption('upper')
  await expect(floor).toHaveValue('upper')
  const editor = page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })
  await editor.getByRole('combobox', { name: /^Objetos colocados/ }).selectOption(server.saved().scene!.fixtures[0].id)
  await expect(editor.getByLabel('X (m)', { exact: true })).toHaveValue('3')
  await expect(editor.getByLabel('X (m)', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Guardar cambios', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(floor).toHaveValue('ground')
  expect(server.writes).toHaveLength(0)
  expect(server.saved().foundationModels?.activeLevelId).toBe('ground')
})
