  await screenshot(second, 'conflict-recovered')
  await page.route(`**/api/projects/${id}`, async route => {
    if (route.request().method() !== 'PUT') return route.continue()
    await route.fetch(); await route.abort('failed')
  }, { times: 1 })
  await page.getByLabel(/^Notas del proyecto/).fill('Servidor guardó; respuesta perdida')
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('No pudimos completar')
  expect((await persisted(page, id)).notes).toBe('Servidor guardó; respuesta perdida')
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('Este proyecto cambió')
  await page.getByRole('button', { name: 'Cargar última versión', exact: true }).click()
  await expect(page.getByLabel(/^Notas del proyecto/)).toHaveValue('Servidor guardó; respuesta perdida')
