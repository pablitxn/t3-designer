test('a ready project keeps original plans inspectable and sends a new source through building correction chat', async ({ page }) => {
  const server = await fixture(page)
  server.seedRun('building')
  const original = server.complete('building')
  server.makeReady(true)
  const before = server.saved()
  await page.goto(projectPath)
  await page.locator('summary').filter({ hasText: /^Planos y fuentes originales$/ }).click()
  await expect(page.getByRole('heading', { name: 'Planos y fuentes originales', exact: true })).toBeVisible()
  await expect(page.getByLabel('Dirección de la propiedad', { exact: true })).toHaveValue('Calle del Parque 100, Córdoba')
  await expect(page.getByLabel('Dirección de la propiedad', { exact: true })).toBeDisabled()
  await expect(page.getByRole('link', { name: /planta-baja.png/ })).toHaveAttribute('href', /\/references\/[^/]+\/image$/)
  await expect(page.getByRole('button', { name: 'Agregar planta', exact: false })).toHaveCount(0)
  await expect(page.getByText('Modelado de vivienda y edificio pendiente', { exact: true })).toHaveCount(0)
  await page.locator('summary').filter({ hasText: /^Agentes de vivienda y edificio$/ }).click()
  const workshop = page.getByTestId('foundation-agent-building')
  await workshop.getByLabel('Tu corrección', { exact: true }).fill('Usá esta nueva ficha catastral: https://example.test/catastro/actualizado. El edificio tiene cuatro plantas.')
  await workshop.getByRole('button', { name: 'Enviar corrección', exact: false }).click()
  await expect.poll(() => server.starts.length).toBe(1)
  expect(server.starts[0].body.parentVersionId).toBe(original.id)
  expect(server.starts[0].body.message).toContain('https://example.test/catastro/actualizado')
  expect(server.saved().foundations).toEqual(before.foundations)
  expect(server.saved().foundationModels).toEqual(before.foundationModels)
  expect(server.writes).toHaveLength(0)
})

test('both independently generated and accepted foundations unlock the ready multi-floor editor', async ({ page }) => {
  const server = await fixture(page)
  await page.goto(projectPath)
  for (const target of ['dwelling', 'building'] as const) {
    const workshop = page.getByTestId(`foundation-agent-${target}`)
    await workshop.getByRole('button', { name: 'Iniciar modelado', exact: false }).click()
    await expect.poll(() => server.starts.some(item => item.body.target === target)).toBe(true)
    server.complete(target)
    await workshop.getByRole('button', { name: 'Usar esta versión', exact: true }).click()
    if (target === 'dwelling') {
      await expect(workshop.getByText('✓ Aplicada al proyecto', { exact: true })).toBeVisible()
      await expect(page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })).toHaveCount(0)
      expect(server.saved().scene).toBeNull()
    }
  }
  await expect(page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Planta', exact: true }).locator('option')).toHaveCount(2)
  await expect(page.getByRole('combobox', { name: /^Objetos colocados/ })).toHaveText('—')
  await expect(page.getByRole('heading', { name: 'Las bases de tu proyecto', exact: true })).toHaveCount(0)
  expect(server.saved().foundations?.dwelling.status).toBe('ready')
  expect(server.saved().foundations?.building.status).toBe('ready')
  expect(server.saved().foundationModels?.levels).toHaveLength(2)
  expect(server.starts.map(item => item.body.target)).toEqual(['dwelling', 'building'])
  expect(server.confirmations).toHaveLength(2)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Diseñá tu departamento', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Planta', exact: true }).locator('option')).toHaveCount(2)
})
