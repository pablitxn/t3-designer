  await expect(workshop.getByText('Fuente oficial · 2026-10-07')).toBeVisible()
  await workshop.getByRole('button', { name: 'Usar esta versión', exact: true }).click()
  await expect(workshop.getByText('✓ Aplicada al proyecto', { exact: true })).toBeVisible()
  expect(server.accepts).toEqual([{ versionId: first.id, revision: 1 }])
  await workshop.getByLabel('Tu corrección', { exact: true }).fill('El edificio tiene cuatro plantas y el patio está al fondo.')
  await workshop.getByRole('button', { name: 'Enviar corrección', exact: false }).click()
